// Функція перевіряє належність точки області
bool isInArea(double x, double y, double a)
{
    // Перевірка, чи знаходиться точка всередині квадрата
    bool inSquare =
        fabs(x) <= a / 2.0 &&
        fabs(y) <= a / 2.0;

    bool result = false;

    // Верхня ліва область
    if (x < 0 && y > 0)
    {
        if (y < -x)
            result = true;
    }

    // Нижня права область
    else if (x > 0 && y < 0)
    {
        result = true;
    }

    // Повернути результат перевірки
    return inSquare && result;
}

// Функція виконання завдання 1
void task1()
{
    int n;              // кількість точок
    double a;           // сторона квадрата
    double x, y;        // координати точки

    int count = 0;      // лічильник точок

    cout << "\n=== TASK 1 ===\n";

    // Введення даних
    cout << "Side of square a = ";
    cin >> a;

    cout << "Number of points n = ";
    cin >> n;

    // Цикл введення та перевірки точок
    for (int i = 1; i <= n; i++)
    {
        cout << "Point " << i << " (x y): ";
        cin >> x >> y;

        // Якщо точка потрапила в область
        if (isInArea(x, y, a))
            count++;
    }

    // Виведення результату
    cout << "Points in area = "
         << count << endl;
}


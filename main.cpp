// Завдання 3 (варіант 33)
// Дослідження збіжності ряду
//======================================================

void task3()
{
    cout << "\n=== TASK 3 ===\n";

    // Мале число для перевірки збіжності
    const double e = 1E-10;

    double sum;     // сума ряду
    double u;       // поточний член ряду

    int n = 1;      // номер елемента

    // Перший член ряду
    u = 10.0 / 5040.0;

    // Початкова сума
    sum = 0.0;

    cout << fixed << setprecision(15);

    // Поки модуль члена не став дуже малим
    while (fabs(u) >= e)
    {
        // Виведення поточного члена
        cout << "u[" << n << "] = "
             << u << endl;

        // Додавання до суми
        sum += u;

        // Перехід до наступного члена
        n++;

        // Рекурентна формула
        u *= (7.0 + 3.0 * n) /
             ((4.0 * n) *
              (4.0 * n - 1.0) *
              (4.0 * n - 2.0) *
              (4.0 * n - 3.0));
    }

    // Виведення результатів
    cout << "\nTerms = "
         << n - 1 << endl;

    cout << "Sum = "
         << sum << endl;
}


// Завдання 2 (варіант 13)
// S = Σ ((x^k + 1) / (k - 1)!)
// Вивести кожний четвертий елемент
//======================================================

void task2()
{
    int n;                  // кількість елементів
    double x;               // значення x

    double sum = 0.0;       // сума ряду

    cout << "\n=== TASK 2 ===\n";

    // Введення даних
    cout << "x = ";
    cin >> x;

    cout << "n = ";
    cin >> n;

    double fact = 1.0;      // (k-1)!

    // Цикл обчислення ряду
    for (int k = 1; k <= n; k++)
    {
        // Обчислення факторіала
        if (k > 1)
            fact *= (k - 1);

        // Поточний елемент ряду
        double u =
            (pow(x, k) + 1.0) / fact;

        // Додавання до суми
        sum += u;

        // Вивести кожний четвертий елемент
        if (k % 4 == 0)
        {
            cout << "u[" << k << "] = "
                 << u << endl;
        }
    }

    // Виведення суми
    cout << "Sum = "
         << sum << endl;
}

